"""Build local WOFF2 shards without changing the LXGW source fonts."""

import re
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "public" / "fonts"
OUT = FONTS / "web"


def glyphs(text):
    return {ord(c) for c in text if c.isprintable()}


def ranges(points):
    runs = []
    for point in sorted(points):
        if runs and point == runs[-1][1] + 1:
            runs[-1][1] = point
        else:
            runs.append([point, point])
    return ",".join(f"U+{start:X}" + (f"-{end:X}" if start != end else "") for start, end in runs)


def write_face(family, file, weight, name, points):
    with TTFont(FONTS / file, recalcTimestamp=False) as font:
        points &= set(font.getBestCmap())
        if not points:
            return ""
        options = subset.Options()
        options.hinting = False
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=points)
        sub.subset(font)
        font.flavor = "woff2"
        filename = f"{name}.woff2"
        font.save(OUT / filename)
    print(f"{filename}: {len(points)} code points, {(OUT / filename).stat().st_size / 1024:.1f} KiB")
    return f'''@font-face {{
  font-family: "{family}";
  src: url("/fonts/web/{filename}") format("woff2");
  font-style: normal;
  font-weight: {weight};
  font-display: swap;
  unicode-range: {ranges(points)};
}}\n'''


def main():
    OUT.mkdir(exist_ok=True)
    latin = set(range(0x20, 0x100))
    core = latin.copy()
    reading = set()
    mono = latin.copy()
    for folder in ["app", "components", "lib"]:
        for path in (ROOT / folder).rglob("*.ts*"):
            core.update(glyphs(path.read_text(encoding="utf-8")))
    for path in (ROOT / "content" / "posts").glob("*.md"):
        text = path.read_text(encoding="utf-8")
        frontmatter = re.search(r"^---[ \t]*\n(.*?)^---[ \t]*$", text, re.M | re.S)
        if frontmatter:
            core.update(glyphs(frontmatter[1]))
        reading.update(glyphs(text))
        for code in re.findall(r"```[\s\S]*?```|`[^`\n]+`", text):
            mono.update(glyphs(code))

    css = ["/* Generated by scripts/optimize-fonts.py. */\n"]
    for weight, style in [(400, "Regular"), (500, "Medium")]:
        font = f"LXGWWenKai-{style}.ttf"
        css.append(write_face("LXGW WenKai Web", font, weight, f"wenkai-ui-{weight}", core.copy()))
        css.append(write_face("LXGW WenKai Web", font, weight, f"wenkai-reading-{weight}", reading - core))
    css.append(write_face("LXGW WenKai Mono Web", "LXGWWenKaiMono-Regular.ttf", 400, "wenkai-mono", mono))
    css.append('''
:root {
  --font-wenkai: "LXGW WenKai Web";
  --font-wenkai-mono: "LXGW WenKai Mono Web";
}
''')
    (ROOT / "app" / "wenkai.generated.css").write_text("\n".join(css), encoding="utf-8")


if __name__ == "__main__":
    main()
